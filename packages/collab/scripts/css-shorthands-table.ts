/**
 * Generates `src/css-shorthands.ts`, the shorthand to longhand table the canonical style order
 * reads (specs/collab.md §3.1). The table is committed rather than read from `@webref/css` at run
 * time: `css.json` is several megabytes and the collab client ships to the browser.
 *
 * `bun run generate:css-shorthands` (`generate-css-shorthands.ts`) rewrites the file;
 * `tests/css-shorthands.test.ts` fails when the committed table differs from what
 * {@link buildShorthandTable} reads out of `@webref/css`, which is how a `@webref/css` bump that
 * moves a shorthand shows up.
 */

import css from "@webref/css";

export type ShorthandTable = Record<string, string[]>;

/** Every property in `@webref/css` that lists longhands, by its kebab-case name, sorted by name. */
export async function buildShorthandTable(): Promise<ShorthandTable> {
  const data = await css.listAll();
  const table: ShorthandTable = {};
  /* The package's types omit `longhands`, which every property record in css.json may carry. */
  const properties: readonly { name: string; longhands?: readonly string[] }[] = data.properties;
  const shorthands = properties
    .filter((property) => (property.longhands?.length ?? 0) > 0)
    .toSorted((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const property of shorthands) {
    table[property.name] = [...(property.longhands ?? [])].toSorted();
  }
  return table;
}

/** The source text of `src/css-shorthands.ts` for `table`. */
export function renderShorthandModule(table: ShorthandTable): string {
  return [
    "/**",
    " * GENERATED by `bun run generate:css-shorthands` from `@webref/css`. Do not edit.",
    " *",
    " * Each CSS shorthand and the longhands it sets, by kebab-case property name. The canonical order of a",
    " * style block (specs/collab.md §3.1) puts a shorthand before its longhands.",
    " */",
    `export const SHORTHAND_LONGHANDS = ${JSON.stringify(table)} satisfies Record<string, readonly string[]>;`,
    "",
  ].join("\n");
}
