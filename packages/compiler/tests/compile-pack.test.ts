/**
 * Compile-pack.test.ts — a directory of component documents as one distributable pack (compiler.md
 * §4.9): a module and a stylesheet per definition, the entry that registers them all, and their
 * Custom Elements Manifest (spec.md §16.8).
 *
 * The last block writes a pack and loads its entry in a DOM, because the point of a pack is that it
 * runs with nothing around it: no site build, no page, no interpreter.
 */

import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import type { JsonValue } from "@jxsuite/schema/types";
import { Window } from "happy-dom";
import type { HTMLElement } from "happy-dom";
import { compileElementPack, writeElementPack } from "../src/compiler";
import type { ElementPack } from "../src/compiler";

const ROOT = resolve(import.meta.dir, "__test-compile-pack__");
const COMPONENTS = resolve(ROOT, "components");

const writeJSON = (path: string, value: JsonValue): void => {
  const full = resolve(ROOT, path);
  mkdirSync(resolve(full, ".."), { recursive: true });
  writeFileSync(full, JSON.stringify(value, null, 2), "utf8");
};

const fileOf = (pack: ElementPack, path: string): string =>
  pack.files.find((file) => file.path === path)?.content ?? "";

beforeAll(() => {
  rmSync(ROOT, { force: true, recursive: true });
  writeJSON("components/x-icon.json", {
    children: [{ tagName: "i", textContent: "${state.name}" }],
    state: { name: "dot" },
    style: { display: "inline-block" },
    tagName: "x-icon",
  });
  // Named before the icon it renders, so the order a pack registers in is not the file order.
  writeJSON("components/a-button.json", {
    $elements: [{ $ref: "./x-icon.json" }],
    attributes: { "data-variant": "${state.variant}" },
    children: [
      { $props: { name: "star" }, tagName: "x-icon" },
      { children: [{ tagName: "slot" }], tagName: "span" },
    ],
    observedAttributes: ["variant"],
    onclick: { $ref: "#/state/onPress" },
    state: {
      onPress: { $prototype: "Function", $src: "pack:/behaviors/press.js" },
      presses: 0,
      size: { attribute: "size", default: "md", type: "string" },
      variant: { default: "secondary", type: "string" },
    },
    style: { '&[data-variant="accent"]': { color: "red" }, display: "inline-flex" },
    tagName: "a-button",
  });
  writeJSON("components/x-panel.json", {
    $shadow: "open",
    children: [{ attributes: { part: "body" }, tagName: "div", textContent: "panel" }],
    style: { display: "block" },
    tagName: "x-panel",
  });
  // Not a document a pack compiles, and ignored when a directory is listed.
  writeFileSync(resolve(COMPONENTS, "notes.md"), "# Notes\n", "utf8");
  writeFileSync(
    resolve(ROOT, "press.js"),
    "export function onPress(state, event) { state.presses += 1; state.last = event.type; }\n",
    "utf8",
  );
});

afterAll(() => {
  rmSync(ROOT, { force: true, recursive: true });
});

const rewriteSrc = (specifier: string): string =>
  specifier.startsWith("pack:/") ? resolve(ROOT, "press.js") : specifier;

describe("compileElementPack", () => {
  test("compiles every document of a directory, each tag after the tags it renders", async () => {
    const pack = await compileElementPack({ components: COMPONENTS, rewriteSrc });
    expect(pack.tags).toEqual(["x-icon", "a-button", "x-panel"]);
    expect(pack.files.map((file) => file.path)).toEqual([
      "x-icon.js",
      "x-icon.css",
      "a-button.js",
      "a-button.css",
      "x-panel.js",
      "x-panel.css",
      "index.js",
      "elements.css",
      "custom-elements.json",
    ]);
    // A module imports the definitions it names as its siblings, and its behaviour as rewritten.
    const button = fileOf(pack, "a-button.js");
    expect(button).toContain("import './x-icon.js';");
    expect(button).toContain(`from '${resolve(ROOT, "press.js")}';`);
    expect(fileOf(pack, "index.js")).toBe(
      "// Generated by @jxsuite/compiler — do not edit manually\n" +
        "import './x-icon.js';\nimport './a-button.js';\nimport './x-panel.js';\n",
    );
  });

  test("writes a stylesheet per definition, and one for the page without the shadow sheets", async () => {
    const pack = await compileElementPack({ components: COMPONENTS, rewriteSrc });
    expect(fileOf(pack, "a-button.css")).toContain('a-button[data-variant="accent"]');
    expect(fileOf(pack, "x-panel.css")).toContain(":host");
    const page = fileOf(pack, "elements.css");
    expect(page).toContain("x-icon {");
    expect(page).toContain("a-button {");
    expect(page).not.toContain(":host");
  });

  test("the manifest names each module under the pack's directory", async () => {
    const pack = await compileElementPack({ components: COMPONENTS, rewriteSrc });
    expect(pack.manifest.modules.map((module) => module.path)).toEqual([
      "dist/a-button.js",
      "dist/x-icon.js",
      "dist/x-panel.js",
    ]);
    const [button, , panel] = pack.manifest.modules;
    expect(button?.declarations[0]).toMatchObject({
      attributes: [{ fieldName: "variant", name: "variant" }],
      customElement: true,
      name: "AButton",
      slots: [{ name: "" }],
    });
    expect(panel?.declarations[0].cssParts).toEqual([{ name: "body" }]);
    expect(fileOf(pack, "custom-elements.json")).toBe(
      `${JSON.stringify(pack.manifest, null, 2)}\n`,
    );
    // An annotation the element does not observe is reported, as a site build reports it.
    expect(pack.warnings).toEqual([
      'a-button: state entry "size" declares attribute "size", but the element does not observe it into that entry (spec.md §16.5); add it to observedAttributes or remove it',
    ]);
  });

  test("packDir places the modules, and an empty one is the package root", async () => {
    const nested = await compileElementPack({
      components: COMPONENTS,
      packDir: "./build/kit/",
      rewriteSrc,
    });
    expect(nested.manifest.modules[0]?.path).toBe("build/kit/a-button.js");
    const flat = await compileElementPack({ components: COMPONENTS, packDir: "", rewriteSrc });
    expect(flat.manifest.modules[0]?.path).toBe("a-button.js");
  });

  test("takes an explicit list of files, and the options a definition compiles with", async () => {
    const pack = await compileElementPack({
      $media: { "--wide": "(min-width: 60rem)" },
      components: [resolve(COMPONENTS, "x-panel.json"), resolve(COMPONENTS, "x-icon.json")],
      defaults: { shadow: "open" },
    });
    expect(pack.tags).toEqual(["x-icon", "x-panel"]);
    // The project default reaches a definition that says nothing: its sheet is a shadow sheet.
    expect(fileOf(pack, "x-icon.css")).toContain(":host");
    expect(fileOf(pack, "elements.css")).toBe("");
  });

  test("refuses a file that is not a component, a duplicate tag and a sibling outside the pack", async () => {
    const message = async (components: string[]): Promise<string> => {
      try {
        await compileElementPack({ components, rewriteSrc });
      } catch (error) {
        return String(error);
      }
      return "";
    };
    writeJSON("other/page.json", { tagName: "main" });
    writeJSON("other/x-icon.json", { tagName: "x-icon" });
    expect(await message([resolve(ROOT, "other/page.json")])).toContain(
      "is not a component: its tagName must contain a hyphen",
    );
    expect(
      await message([resolve(COMPONENTS, "x-icon.json"), resolve(ROOT, "other/x-icon.json")]),
    ).toContain('both declare the tagName "x-icon"');
    expect(await message([resolve(COMPONENTS, "a-button.json")])).toContain(
      '"./x-icon.json" names a component outside the pack',
    );
    expect(await message([resolve(COMPONENTS, "notes.md")])).toContain(
      "is not a .json or .jxn document",
    );
  });
});

describe("a written pack", () => {
  const OUT = resolve(ROOT, "dist");
  let win: Window;

  /** A compiled element with the state its module builds. */
  type PackElement = HTMLElement & { state: Record<string, JsonValue> };
  function isPackElement(element: HTMLElement): element is PackElement {
    return "state" in element;
  }

  beforeAll(async () => {
    win = new Window({ url: "https://example.test" });
    Object.assign(globalThis, {
      CustomEvent: win.CustomEvent,
      Element: win.Element,
      Event: win.Event,
      HTMLElement: win.HTMLElement,
      Node: win.Node,
      customElements: win.customElements,
      document: win.document,
      window: win.window,
    });
    const pack = await compileElementPack({ components: COMPONENTS, rewriteSrc });
    const written = await writeElementPack(pack, OUT);
    expect(written).toHaveLength(pack.files.length);
    await import(resolve(OUT, "index.js"));
  }, 30_000);

  test("is on disk as the pack lists it", () => {
    for (const file of ["a-button.js", "a-button.css", "index.js", "elements.css"]) {
      expect(existsSync(resolve(OUT, file))).toBe(true);
    }
    expect(readFileSync(resolve(OUT, "custom-elements.json"), "utf8")).toContain('"2.1.0"');
  });

  test("its entry registers every element, and an element runs with nothing around it", () => {
    for (const tag of ["x-icon", "a-button", "x-panel"]) {
      expect(win.customElements.get(tag)).toBeDefined();
    }
    const button = win.document.createElement("a-button");
    button.setAttribute("variant", "accent");
    button.textContent = "Go";
    win.document.body.append(button);
    if (!isPackElement(button)) {
      throw new Error("Expected <a-button> to carry its state");
    }
    // The root attribute follows the observed one, the sibling renders, the slot takes the text.
    expect(button.dataset.variant).toBe("accent");
    expect(button.querySelector("x-icon i")?.textContent).toBe("star");
    expect(button.querySelector("span")?.textContent.trim()).toBe("Go");
    // The behaviour module the pack imports is the root handler.
    button.dispatchEvent(new win.Event("click"));
    expect(button.state.presses).toBe(1);
    expect(button.state.last).toBe("click");
    button.remove();
  });
});
