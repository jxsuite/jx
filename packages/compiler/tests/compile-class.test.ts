import { describe, expect, test } from "bun:test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { validateClass } from "@jxsuite/schema";
import { compileClassJson } from "../src/targets/compile-class";
import { parseClassDef } from "@jxsuite/schema/parse";
import type { JsonObject, JsonValue, JxClassDef } from "@jxsuite/schema/types";

/** A directory for compiled class modules a test imports; the caller removes it. */
function moduleDir(): string {
  return mkdtempSync(join(tmpdir(), "jx-class-module-"));
}

/** Write a compiled class module into `dir` and return the URL to import it by. */
function writeModule(dir: string, name: string, source: string): string {
  const path = join(dir, name);
  writeFileSync(path, source, "utf8");
  return pathToFileURL(path).href;
}

// ─── compileClassJson — Basic class generation ──────────────────────────────

describe("compileClassJson — basic", () => {
  test("throws when title is missing", () => {
    expect(() => compileClassJson({ $prototype: "Class" })).toThrow("missing title");
  });

  test("generates class declaration with title", () => {
    const result = compileClassJson({ $prototype: "Class", title: "Foo" });
    expect(result).toContain("class Foo {");
    expect(result).toContain("export { Foo };");
    expect(result).toContain("export default Foo;");
  });

  test("includes generation comment", () => {
    const result = compileClassJson({ $prototype: "Class", title: "Bar" });
    expect(result).toContain("// Generated by @jxsuite/compiler");
  });

  test("includes $id as source comment", () => {
    const result = compileClassJson({
      $id: "https://example.com/Bar.class.json",
      $prototype: "Class",
      title: "Bar",
    });
    expect(result).toContain("// Source: https://example.com/Bar.class.json");
  });

  test("no $id omits source comment", () => {
    const result = compileClassJson({ $prototype: "Class", title: "Baz" });
    expect(result).not.toContain("// Source:");
  });
});

// ─── compileClassJson — extends ─────────────────────────────────────────────

describe("compileClassJson — extends", () => {
  test("no extends generates plain class", () => {
    const result = compileClassJson({ $prototype: "Class", title: "Foo" });
    expect(result).toContain("class Foo {");
    expect(result).not.toContain("extends");
  });

  test("string extends generates extends clause", () => {
    const result = compileClassJson({
      $prototype: "Class",
      extends: "HTMLElement",
      title: "Foo",
    });
    expect(result).toContain("class Foo extends HTMLElement {");
  });

  test("extends Object is treated as no extends", () => {
    const result = compileClassJson({
      $prototype: "Class",
      extends: "Object",
      title: "Foo",
    });
    expect(result).toContain("class Foo {");
    expect(result).not.toContain("extends Object");
  });

  test("$ref extends extracts class name from filename", () => {
    const result = compileClassJson({
      $prototype: "Class",
      extends: { $ref: "./Parent.class.json" },
      title: "Child",
    });
    expect(result).toContain("class Child extends Parent {");
    expect(result).toContain('import Parent from "./Parent.js";');
  });

  test("a $ref base's import drops the fragment and is relative to the document", () => {
    const bare = compileClassJson({
      $prototype: "Class",
      extends: { $ref: "Parent.class.json#/$defs/x" },
      title: "Child",
    });
    expect(bare).toContain('import Parent from "./Parent.js";');
    const nested = compileClassJson({
      $prototype: "Class",
      extends: { $ref: "../base/Parent.class.json" },
      title: "Child",
    });
    expect(nested).toContain('import Parent from "../base/Parent.js";');
    const absolute = compileClassJson({
      $prototype: "Class",
      extends: { $ref: "https://example.com/Parent.class.json" },
      title: "Child",
    });
    expect(absolute).toContain('import Parent from "https://example.com/Parent.js";');
  });

  test("a $ref base class is imported and extended", async () => {
    const dir = moduleDir();
    try {
      // The base's title differs from its file name, so only the default import can link the two.
      const parentUrl = writeModule(
        dir,
        "Parent.js",
        compileClassJson({
          $defs: { methods: { hello: { body: "return 'base';", role: "method" } } },
          $prototype: "Class",
          title: "Base",
        }),
      );
      const childUrl = writeModule(
        dir,
        "Child.js",
        compileClassJson({
          $prototype: "Class",
          extends: { $ref: "./Parent.class.json" },
          title: "Child",
        }),
      );
      const { default: Base } = await import(parentUrl);
      const { Child } = await import(childUrl);
      const child = new Child();
      expect(child instanceof Base).toBe(true);
      expect(child.hello()).toBe("base");
    } finally {
      rmSync(dir, { force: true, recursive: true });
    }
  });

  test("a string base is a global the host supplies, and is not imported", () => {
    const result = compileClassJson({
      $prototype: "Class",
      extends: "HTMLElement",
      title: "Foo",
    });
    expect(result).not.toContain("import ");
  });

  test("$ref with unrecognized pattern falls back to Object", () => {
    const result = compileClassJson({
      $prototype: "Class",
      extends: { $ref: "./weird" },
      title: "Child",
    });
    expect(result).toContain("class Child {");
    expect(result).not.toContain("extends");
    expect(result).not.toContain("import ");
  });

  test("extends as unknown object type falls back to Object", () => {
    const classDef: JsonObject = {
      $prototype: "Class",
      extends: { something: "else" },
      title: "Child",
    };
    /*
     * SAFETY: JxClassDef types `extends` as string | JxRef and this object is neither, which is the
     * unvalidated input under test; resolveBaseClass reads only `$ref` (absent here) from it.
     */
    const result = compileClassJson(classDef as JxClassDef);
    expect(result).toContain("class Child {");
  });

  test("super() call emitted for non-Object base", () => {
    const result = compileClassJson({
      $prototype: "Class",
      extends: "HTMLElement",
      title: "Foo",
    });
    expect(result).toContain("super();");
  });

  test("super() with arguments from superCall", () => {
    const result = compileClassJson({
      $defs: {
        constructor: {
          $prototype: "Function",
          role: "constructor",
          superCall: { arguments: ["config.a", "config.b"] },
        },
      },
      $prototype: "Class",
      extends: "Base",
      title: "Foo",
    });
    expect(result).toContain("super(config.a, config.b);");
  });
});

